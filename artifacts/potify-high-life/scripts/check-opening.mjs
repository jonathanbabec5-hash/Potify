import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { SAVE_KEY } from '../src/game/store.ts';
import { HIGH_CAMERA, FIRST_LIGHT_YAW } from '../src/game/opening.ts';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const run=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE,args:JSON.parse(process.env.CHROMIUM_ARGS||'[]')});
const url=pathToFileURL(resolve(process.argv[2]||'dist/offline/POTIFY-A-Wonderful-High-Life.html')).href;
const read=p=>p.evaluate(k=>JSON.parse(localStorage.getItem(k)),SAVE_KEY);
const delay=ms=>new Promise(r=>setTimeout(r,ms));
const out=process.env.QA_OUT;
if(out)await mkdir(out,{recursive:true});
const fault=[];
async function enter(mobile,reducedMotion){
 const settings=mobile?{viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true}:{viewport:{width:1280,height:720}};
 const ctx=await run.newContext({...settings,reducedMotion,offline:true});
 const p=await ctx.newPage();
 p.setDefaultTimeout(28000);
 p.on('pageerror',e=>fault.push(e.message));
 await p.goto(url);
 await p.getByTestId('button-continue').click();
 await p.getByTestId('input-name').fill('Canopy tester');
 await p.getByTestId('checkbox-ack').click();
 await p.getByTestId('button-begin').click();
 await p.getByTestId('opening-scene').waitFor({state:'visible'});
 return {ctx,p};
}
try{
 assert.ok(FIRST_LIGHT_YAW < -.3);
 const {p,ctx}=await enter(true,'no-preference');
 const when=Date.now();
 assert.equal((await read(p)).settings.camera,HIGH_CAMERA);
 assert.equal((await read(p)).settings.showHud,false);
 assert.equal(await p.locator('[data-testid="toast"]').count(),0);
 await p.getByTestId('opening-turn').waitFor();
 await delay(Math.max(0,6000-(Date.now()-when)));
 assert.equal(await p.getByTestId('opening-dialogue').count(),0);
 assert.equal(await p.getByTestId('guidance-layer').count(),0);
 const image=await p.getByRole('img',{name:/Sunrise pours/}).evaluate(el=>el.naturalWidth);
 assert.equal(image,1280);
 const movie=p.locator('.opening-film video');
 const media=await movie.evaluate(v=>({ready:v.readyState,error:v.error?.message,duration:v.duration,width:v.videoWidth}));
 if(out) await p.screenshot({path:out+'/opening-phone.png'});
 await p.getByTestId('opening-turn').tap();
 await p.getByTestId('opening-dialogue').waitFor();
 assert.match(await p.getByTestId('opening-dialogue').innerText(),/Tessa Bloom/);
 if(media.ready>=2){
  const ended=await movie.evaluate(v=>v.currentTime);
  assert.ok(ended>.50,'pan actually played to the reveal');
 }
 for(let i=0;i<3;i++)await p.getByTestId('opening-next').tap();
 await p.getByTestId('joystick').waitFor();
 const cue=p.getByTestId('quiet-first-objective');
 assert.equal(await p.getByText('Opening Roof 7B',{exact:true}).count(),0);
 await cue.getByText('Read the lease on the desk',{exact:true}).waitFor();
 assert.equal(await p.getByTestId('guidance-layer').count(),0);
 assert.equal(await p.getByTestId('toast').count(),0);
 const lease=p.getByTestId('button-action').filter({hasText:'Lease for Roof 7B'});
 await lease.waitFor();
 if(out)await p.screenshot({path:out+'/rear-phone.png'});
 await lease.tap();
 assert.equal((await read(p)).story.leaseRead,true);
 await p.reload();
 await p.getByTestId('button-continue').tap();
 await p.getByTestId('joystick').waitFor();
 assert.equal(await p.getByTestId('opening-scene').count(),0);
 await cue.getByText('Take the lift to R',{exact:true}).waitFor();
 assert.equal(await p.getByTestId('toast').count(),0);
 assert.equal((await read(p)).settings.camera,HIGH_CAMERA);
 console.log('PASS phone-sized Chromium: cinematic hold, handoff, quiet first objective, lease, next objective, reload; media:',JSON.stringify(media));
 await ctx.close();
 const d=await enter(false,'reduce');
 await d.p.getByRole('button',{name:'Mute intro'}).click();
 await d.p.getByTestId('opening-turn').press('Enter');
 await d.p.getByTestId('opening-dialogue').waitFor();
 await d.p.getByTestId('opening-skip').click();
 await d.p.getByTestId('quiet-first-objective').getByText('Read the lease on the desk',{exact:true}).waitFor();
 assert.equal(await d.p.getByTestId('guidance-layer').count(),0);
 const readPrompt=d.p.getByTestId('button-prompt').filter({hasText:'Lease for Roof 7B'});
 await readPrompt.waitFor();
 if(out)await d.p.screenshot({path:out+'/rear-desktop.png'});
 await d.p.keyboard.press('KeyE');
 assert.equal((await read(d.p)).story.leaseRead,true);
 console.log('PASS desktop: reduced-motion, mute, skip, quiet lease prompt and keyboard interaction.');
 assert.deepEqual(fault,[]);
 await d.ctx.close();
}finally{await run.close();}
